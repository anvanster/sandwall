// RunDir is where iproute2 and vishvananda/netns keep named namespaces.
const RunDir = "/var/run/netns"

// EtcNetnsDir holds per-namespace overrides bind-mounted by `ip netns exec`.
const EtcNetnsDir = "/etc/netns"

// Create builds the netns, veth pair, addresses, routes and sysctls for a
// sandbox. It is idempotent and repairs a partially created sandbox.
func Create(sb addressing.Sandbox) error {
	nsh, err := ensureNamed(sb.Netns)
	if err != nil {
		return fmt.Errorf("netns %s: %w", sb.Netns, err)
	}
	defer nsh.Close()

	nl, err := netlink.NewHandleAt(nsh)
	if err != nil {
		return fmt.Errorf("netlink handle in %s: %w", sb.Netns, err)
	}
	defer nl.Close()

	if err := ensureVeth(sb, nsh, nl); err != nil {
		return err
	}

	host, err := netlink.LinkByName(sb.HostVeth)
	if err != nil {
		return fmt.Errorf("%s: %w", sb.HostVeth, err)
	}
	if err := writeSysctl(fmt.Sprintf("net/ipv6/conf/%s/disable_ipv6", sb.HostVeth), "1"); err != nil {
		return err
	}
	if err := netlink.AddrReplace(host, addr(sb.HostAddr, sb.Transfer.Bits())); err != nil {
		return fmt.Errorf("address on %s: %w", sb.HostVeth, err)
	}
	if err := netlink.LinkSetUp(host); err != nil {
		return fmt.Errorf("up %s: %w", sb.HostVeth, err)
	}

	err = inNetns(nsh, func() error {
		for _, k := range []string{"net/ipv6/conf/all/disable_ipv6", "net/ipv6/conf/default/disable_ipv6"} {
			if err := writeSysctl(k, "1"); err != nil {
				return err
			}
		}
		return nil
	})
	if err != nil {
		return fmt.Errorf("sysctls in %s: %w", sb.Netns, err)
	}

	lo, err := nl.LinkByName("lo")
	if err != nil {
		return fmt.Errorf("lo in %s: %w", sb.Netns, err)
	}
	if err := nl.LinkSetUp(lo); err != nil {
		return fmt.Errorf("up lo in %s: %w", sb.Netns, err)
	}
	peer, err := nl.LinkByName(sb.NsVeth)
	if err != nil {
		return fmt.Errorf("%s in %s: %w", sb.NsVeth, sb.Netns, err)
	}
	if err := nl.AddrReplace(peer, addr(sb.NsAddr, sb.Transfer.Bits())); err != nil {
		return fmt.Errorf("address on %s: %w", sb.NsVeth, err)
	}
	if err := nl.LinkSetUp(peer); err != nil {
		return fmt.Errorf("up %s: %w", sb.NsVeth, err)
	}
	route := &netlink.Route{LinkIndex: peer.Attrs().Index, Gw: sb.HostAddr.AsSlice()}
	if err := nl.RouteReplace(route); err != nil {
		return fmt.Errorf("default route in %s: %w", sb.Netns, err)
	}
	return nil
}

// ensureVeth makes sure veth-h<k> exists in the host netns and its peer
// veth-s<k> is inside the sandbox netns, recreating the pair otherwise.
func ensureVeth(sb addressing.Sandbox, nsh netns.NsHandle, nl *netlink.Handle) error {
	if host, err := netlink.LinkByName(sb.HostVeth); err == nil {
		if _, err := nl.LinkByName(sb.NsVeth); err == nil {
			if _, ok := host.(*netlink.Veth); ok {
				return nil
			}
		}
		if err := netlink.LinkDel(host); err != nil {
			return fmt.Errorf("remove stale %s: %w", sb.HostVeth, err)
		}
	}
	la := netlink.NewLinkAttrs()
	la.Name = sb.HostVeth
	veth := &netlink.Veth{LinkAttrs: la, PeerName: sb.NsVeth, PeerNamespace: netlink.NsFd(int(nsh))}
	if err := netlink.LinkAdd(veth); err != nil {
		return fmt.Errorf("create veth %s/%s: %w", sb.HostVeth, sb.NsVeth, err)
	}
	return nil
}

// Destroy kills any process left in the sandbox netns, then removes the veth
// pair, the netns and its /etc/netns directory. Missing pieces are ignored.
func Destroy(sb addressing.Sandbox) error {
	var errs []error
	if err := killNetnsProcesses(sb.Netns); err != nil {
		errs = append(errs, err)
	}
	for _, name := range []string{sb.HostVeth, sb.IFB} {
		if link, err := netlink.LinkByName(name); err == nil {
			if err := netlink.LinkDel(link); err != nil {
				errs = append(errs, fmt.Errorf("delete %s: %w", name, err))
			}
		}
	}
	if err := deleteNamed(sb.Netns); err != nil {
		errs = append(errs, fmt.Errorf("delete netns %s: %w", sb.Netns, err))
	}
	if err := os.RemoveAll(filepath.Join(EtcNetnsDir, sb.Netns)); err != nil {
		errs = append(errs, err)
	}
	return errors.Join(errs...)
}

// WriteResolvConf points exec-mode processes at the sandbox's DNS proxy.
// `ip netns exec` bind-mounts this file over /etc/resolv.conf.
func WriteResolvConf(sb addressing.Sandbox) error {
	dir := filepath.Join(EtcNetnsDir, sb.Netns)
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	content := fmt.Sprintf("# generated by sandwall\nnameserver %s\n", sb.HostAddr)
	return writeFileAtomic(filepath.Join(dir, "resolv.conf"), []byte(content), 0o644)
}

// Leftovers lists every sandbox index that still has any sandwall-named
// netns, host veth, IFB or /etc/netns directory on this host.
func Leftovers() ([]int, error) {
	seen := map[int]bool{}
	for _, dir := range []string{RunDir, EtcNetnsDir} {
		entries, err := os.ReadDir(dir)
		if err != nil && !errors.Is(err, fs.ErrNotExist) {
			return nil, err
		}
		for _, e := range entries {
			if k, ok := addressing.IndexFromNetns(e.Name()); ok {
				seen[k] = true
			}
		}
	}
	links, err := netlink.LinkList()
	if err != nil {
		return nil, err
	}
	for _, l := range links {
		if k, ok := addressing.IndexFromHostVeth(l.Attrs().Name); ok {
			seen[k] = true
		}
		if k, ok := addressing.IndexFromIFB(l.Attrs().Name); ok {
			seen[k] = true
		}
	}
	out := make([]int, 0, len(seen))
	for k := range seen {
		out = append(out, k)
	}
	sort.Ints(out)
	return out, nil
}

// deleteNamed unmounts and removes a named netns. Unlike netns.DeleteNamed
// it tolerates a missing or never-mounted file.
func deleteNamed(name string) error {
	path := filepath.Join(RunDir, name)
	if err := unix.Unmount(path, unix.MNT_DETACH); err != nil &&
		!errors.Is(err, unix.ENOENT) && !errors.Is(err, unix.EINVAL) {
		return err
	}
	if err := os.Remove(path); err != nil && !errors.Is(err, fs.ErrNotExist) {
		return err
	}
	return nil
}

// ensureNamed returns a handle to the named netns, creating it if needed.
func ensureNamed(name string) (netns.NsHandle, error) {
	if h, err := netns.GetFromName(name); err == nil {
		var st unix.Statfs_t
		if err := unix.Fstatfs(int(h), &st); err == nil && st.Type == unix.NSFS_MAGIC {
			return h, nil
		}
		// A leftover file that is not a mounted netns: replace it.
		h.Close()
		if err := deleteNamed(name); err != nil {
			return netns.None(), err
		}
	}
	var created netns.NsHandle
	err := withLockedThread(func() error {
		var err error
		created, err = netns.NewNamed(name)
		return err
	})
	return created, err
}

// inNetns runs fn with the calling OS thread switched into nsh.
func inNetns(nsh netns.NsHandle, fn func() error) error {
	return withLockedThread(func() error {
		if err := netns.Set(nsh); err != nil {
			return err
		}
		return fn()
	})
}

// withLockedThread runs fn on a locked OS thread and restores the thread's
// original netns afterwards. If restoring fails the thread stays locked, so
// the Go runtime discards it when the goroutine exits instead of reusing a
// thread that is in the wrong namespace.
func withLockedThread(fn func() error) error {
	errc := make(chan error, 1)
	go func() {
		runtime.LockOSThread()
		orig, err := netns.Get()
		if err != nil {
			runtime.UnlockOSThread()
			errc <- err
			return
		}
		defer orig.Close()
		fnErr := fn()
		if err := netns.Set(orig); err != nil {
			errc <- errors.Join(fnErr, fmt.Errorf("restore netns: %w", err))
			return // thread intentionally left locked
		}
		runtime.UnlockOSThread()
		errc <- fnErr
	}()
	return <-errc
}

// killNetnsProcesses SIGKILLs every process whose network namespace is the
// named sandbox netns, so destroy leaves nothing running behind.
func killNetnsProcesses(name string) error {
	_, err := signalNetnsProcesses(name, unix.SIGKILL)
	return err
}

// FreezeProcesses SIGSTOPs every process in the sandbox's netns. A process
// forked while the first pass runs is caught by a later one; passes repeat
// until one finds nothing new. It returns how many processes were stopped.
func FreezeProcesses(sb addressing.Sandbox) (int, error) {
	seen := map[int]bool{}
	for range 5 {
		pids, err := signalNetnsProcesses(sb.Netns, unix.SIGSTOP)
		if err != nil {
			return len(seen), err
		}
		fresh := false
		for _, p := range pids {
			if !seen[p] {
				seen[p], fresh = true, true
			}
		}
		if !fresh {
			break
		}
	}
	return len(seen), nil
}

// ThawProcesses SIGCONTs every process in the sandbox's netns.
func ThawProcesses(sb addressing.Sandbox) error {
	_, err := signalNetnsProcesses(sb.Netns, unix.SIGCONT)
	return err
}

// signalNetnsProcesses sends sig to every process whose network namespace
// is the named netns and returns their pids.
func signalNetnsProcesses(name string, sig unix.Signal) ([]int, error) {
	var target syscall.Stat_t
	if err := syscall.Stat(filepath.Join(RunDir, name), &target); err != nil {
		if errors.Is(err, fs.ErrNotExist) {
			return nil, nil
		}
		return nil, err
	}
	procs, err := os.ReadDir("/proc")
	if err != nil {
		return nil, err
	}
	self := os.Getpid()
	var pids []int
	for _, p := range procs {
		pid, err := strconv.Atoi(p.Name())
		if err != nil || pid == self {
			continue
		}
		var st syscall.Stat_t
		if err := syscall.Stat(fmt.Sprintf("/proc/%d/ns/net", pid), &st); err != nil {
			continue
		}
		if st.Ino == target.Ino && st.Dev == target.Dev {
			if unix.Kill(pid, sig) == nil {
				pids = append(pids, pid)
			}
		}
	}
	return pids, nil
}

func addr(a netip.Addr, bits int) *netlink.Addr {
	return &netlink.Addr{IPNet: &net.IPNet{IP: a.AsSlice(), Mask: net.CIDRMask(bits, 32)}}
}

func writeSysctl(key, value string) error {
	path := filepath.Join("/proc/sys", key)
	if err := os.WriteFile(path, []byte(value), 0o644); err != nil {
		return fmt.Errorf("sysctl %s=%s: %w", strings.ReplaceAll(key, "/", "."), value, err)
	}
	return nil
}

func readSysctl(key string) (string, error) {
	b, err := os.ReadFile(filepath.Join("/proc/sys", key))
	if err != nil {
		return "", err
	}
	return strings.TrimSpace(string(b)), nil
}

func writeFileAtomic(path string, data []byte, perm os.FileMode) error {
	tmp, err := os.CreateTemp(filepath.Dir(path), ".tmp-*")
	if err != nil {
		return err
	}
	defer os.Remove(tmp.Name())
	if _, err := tmp.Write(data); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Chmod(perm); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	return os.Rename(tmp.Name(), path)
}

// SetupVM adds VM-mode plumbing to a sandbox netns: tap0 (owned by the VMM's
// uid/gid, 172.16.0.1/30) and IPv4 forwarding inside the netns. It is
// idempotent; an existing tap0 is kept because a running VM holds it open.
func SetupVM(sb addressing.Sandbox, uid int) error {
	nsh, err := netns.GetFromName(sb.Netns)
	if err != nil {
		return fmt.Errorf("netns %s: %w", sb.Netns, err)
	}
	defer nsh.Close()
	err = inNetns(nsh, func() error {
		if err := writeSysctl("net/ipv4/ip_forward", "1"); err != nil {
			return err
		}
		tap, err := netlink.LinkByName(addressing.TapName)
		if err != nil {
			t := &netlink.Tuntap{
				LinkAttrs: netlink.LinkAttrs{Name: addressing.TapName},
				Mode:      netlink.TUNTAP_MODE_TAP,
				Flags:     netlink.TUNTAP_NO_PI | netlink.TUNTAP_VNET_HDR | netlink.TUNTAP_ONE_QUEUE,
				Owner:     uint32(uid),
				Group:     uint32(uid),
			}
			// Tuntap creation is an ioctl on /dev/net/tun, so it must run
			// on a thread inside the netns rather than via a netns handle.
			if err := netlink.LinkAdd(t); err != nil {
				return fmt.Errorf("create %s: %w", addressing.TapName, err)
			}
			if tap, err = netlink.LinkByName(addressing.TapName); err != nil {
				return err
			}
		}
		if err := netlink.AddrReplace(tap, addr(addressing.TapAddr, 30)); err != nil {
			return fmt.Errorf("address on %s: %w", addressing.TapName, err)
		}
		return netlink.LinkSetUp(tap)
	})
	if err != nil {
		return fmt.Errorf("vm plumbing in %s: %w", sb.Netns, err)
	}
	return nil
}
